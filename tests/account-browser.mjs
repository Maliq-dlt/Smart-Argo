  assert.match(author,/^[0-9a-f-]{36}$/)
  sql(`INSERT INTO plant_profile(id,species_variety,context_scope) VALUES('${plantId}','Synthetic browser fixture ${run}','Software UI test only; not agronomic advice'); INSERT INTO contribution(id,profile_id,author_account_id,source_method_license,evidence_ref,proposed_parameters,status) VALUES('${contributionId}','${plantId}','${author}','Synthetic in-repository software fixture; test use only','tests/account-browser.mjs','{}','approved'); INSERT INTO profile_version(id,profile_id,contribution_id,version,parameters_and_scope,evidence_level) VALUES('${profileId}','${plantId}','${contributionId}',1,'{}','Synthetic software fixture; not field validated');`)
  await page.reload(); await curtainOpen(page)
  await profileSection(page,'Produk')
