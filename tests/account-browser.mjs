import assert from 'node:assert/strict'
import { randomUUID, randomBytes, generateKeyPairSync, sign } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { createRequire } from 'node:module'
import { mkdir, writeFile, readFile } from 'node:fs/promises'
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright')
// The site curtain (loading screen) covers the first paint; interact only once it has lifted, like a visitor would.
const curtainOpen = page => page.waitForFunction(() => { const c = document.querySelector('.curtain'); return !c || c.dataset.state === 'open' })
const browser = await chromium.launch({ headless:true,channel:'chrome' })
const sql = input => execFileSync('docker',['exec','-i','smart-agro-phase1-db-1','psql','-X','-q','-At','-v','ON_ERROR_STOP=1','-U','postgres'],{input,encoding:'utf8',stdio:['pipe','pipe','pipe']}).trim()
const id=randomUUID(),device=randomUUID(),run=randomUUID().slice(0,8),serial=`TEST-UI-${run}`.toUpperCase()
const email=`browser-${run}@example.test`, password=randomBytes(20).toString('base64url'),code=randomBytes(24).toString('base64url')
const keys=generateKeyPairSync('ed25519'),raw=Buffer.from(keys.publicKey.export({format:'jwk'}).x,'base64url').toString('base64')
sql(`INSERT INTO product(id,serial_public,variant,issuer_signature) VALUES('${id}','${serial}','single_pot','local-browser-test'); INSERT INTO device(id,product_id,public_key) VALUES('${device}','${id}','${raw}'); INSERT INTO activation(product_id,secret_hash) VALUES('${id}',encode(digest('${code}','sha256'),'hex'));`)
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'})
const errors=[],report=[]
const telemetry=panelLocator => panelLocator.getByRole('region',{name:'Data perangkat tersimpan',exact:true})
const profileId=randomUUID(),plantId=randomUUID(),contributionId=randomUUID()
page.on('pageerror',e=>errors.push(e.message))
const panel=page.getByRole('region',{name:'Akun & kepemilikan produk online',exact:true})
try{
  await page.goto(process.env.TEST_URL || 'http://127.0.0.1:5173/#ekosistem'); await curtainOpen(page)
  await panel.getByLabel('Email',{exact:true}).fill(email)
  await panel.getByLabel('Kata sandi',{exact:true}).fill(password)
  await panel.getByRole('button',{name:'Daftar',exact:true}).click()
  await panel.getByRole('button',{name:'Keluar',exact:true}).waitFor()
  // Synthetic UI fixture: explicit software-test provenance; no agronomic validation claim.
  const author=sql(`SELECT a.id FROM account a JOIN auth.users u ON u.id=a.auth_user_id WHERE u.email='${email}';`)
  assert.match(author,/^[0-9a-f-]{36}$/)
  sql(`INSERT INTO plant_profile(id,species_variety,context_scope) VALUES('${plantId}','Synthetic browser fixture ${run}','Software UI test only; not agronomic advice'); INSERT INTO contribution(id,profile_id,author_account_id,source_method_license,evidence_ref,proposed_parameters,status) VALUES('${contributionId}','${plantId}','${author}','Synthetic in-repository software fixture; test use only','tests/account-browser.mjs','{}','approved'); INSERT INTO profile_version(id,profile_id,contribution_id,version,parameters_and_scope,evidence_level) VALUES('${profileId}','${plantId}','${contributionId}',1,'{}','Synthetic software fixture; not field validated');`)
  await page.reload()
  await panel.getByRole('button',{name:'Keluar',exact:true}).waitFor()
  await panel.getByLabel('Nomor seri produk / QR',{exact:true}).fill(serial)
  await panel.getByRole('button',{name:'Minta challenge perangkat',exact:true}).click()
  const challenge=panel.locator('textarea')
  await challenge.waitFor()
  const text=await challenge.inputValue(),signature=sign(null,Buffer.from(text),keys.privateKey).toString('base64')
  await panel.getByLabel('Kode aktivasi tersegel',{exact:true}).fill(code)
  await panel.getByLabel('Tanda tangan perangkat (base64)',{exact:true}).fill(signature)
  await panel.getByRole('button',{name:'Verifikasi & klaim produk',exact:true}).click()
  await panel.getByRole('listitem').filter({hasText:serial}).waitFor()
  assert.equal(await panel.getByLabel('Kode aktivasi tersegel',{exact:true}).count(),0)
  await page.reload()
  await panel.getByRole('listitem').filter({hasText:serial}).waitFor()
  report.push('signup, signed claim, cleared secrets and durable refresh passed')
  const devicePanel=telemetry(panel)
  await devicePanel.getByRole('combobox',{name:'Produk',exact:true}).selectOption(id)
  await devicePanel.getByRole('combobox',{name:'Profil tanaman',exact:true}).selectOption(profileId)
  await devicePanel.getByLabel('Label lokasi unit',{exact:true}).fill('Synthetic test unit')
  await devicePanel.getByRole('button',{name:'Buat unit',exact:true}).click()
  await devicePanel.getByRole('status').filter({hasText:'Unit berhasil dibuat'}).waitFor()
  const unitId=sql(`SELECT id FROM unit WHERE product_id='${id}';`)
  assert.match(unitId,/^[0-9a-f-]{36}$/)
  // Backdate only this synthetic ownership fixture to exercise a visibly stale retained sample.
  sql(`UPDATE ownership SET start_at=clock_timestamp()-interval '20 minutes' WHERE product_id='${id}' AND end_at IS NULL;`)
  const payload=JSON.stringify({domain:'smart-agro.telemetry.v2',schema_version:2,source:'device',device_id:device,unit_id:unitId,boot_id:randomUUID(),sequence:1,measured_at:new Date(Date.now()-6*60000).toISOString(),clock_status:'unsynced',sensors:{moisture:{status:'ok',value:42},soil_temperature:{status:'error',value:null,error:'Synthetic probe error'},soil_ph:{status:'not_measured',value:null}}})
  const sent=await fetch('http://127.0.0.1:54321/functions/v1/telemetry-ingest',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({payload,signature:sign(null,Buffer.from(payload),keys.privateKey).toString('base64')})})
  assert.equal(sent.status,200,await sent.text())
  const unitKey=`${unitId}:${device}`
  await devicePanel.getByRole('combobox',{name:'Unit & perangkat milik saya',exact:true}).selectOption(unitKey)
  await devicePanel.getByRole('button',{name:'Muat ulang bacaan',exact:true}).click()
  await devicePanel.locator('summary').filter({hasText:'3 bacaan terakhir'}).click()
  await devicePanel.getByText('Galat perangkat: Synthetic probe error',{exact:true}).waitFor()
  assert.equal(await devicePanel.getByText('Suhu tanah: NULL',{exact:true}).count(),1)
  assert.equal(await devicePanel.getByText('pH tanah: NULL',{exact:true}).count(),1)
  assert.equal(await devicePanel.getByText('Indeks kelembapan: 42/100',{exact:true}).count(),1)
  assert.equal(await devicePanel.getByText(/belum tersinkron.*Usang/).count(),3)
  assert.equal(await devicePanel.getByText(/Diukur .* UTC · Diterima .* UTC/).count(),3)
  await page.reload()
  await devicePanel.getByRole('combobox',{name:'Unit & perangkat milik saya',exact:true}).selectOption(unitKey)
  await devicePanel.locator('summary').filter({hasText:'3 bacaan terakhir'}).click()
  await devicePanel.getByText('Galat perangkat: Synthetic probe error',{exact:true}).waitFor()
  report.push('synthetic published profile -> UI unit creation -> real Ed25519 ingestion -> NULL/error/unsynced/stale/UTC history; unit persists after refresh')
  const explanation=devicePanel.getByRole('region',{name:'Penjelasan berbasis bukti',exact:true})
  // Deliberate browser transport fault: no fabricated service result or success state.
  await page.route('**/functions/v1/unit-explanation',route=>route.abort('failed'))
  await explanation.getByRole('button',{name:'Buat penjelasan berbasis bukti',exact:true}).click()
  await explanation.getByRole('status').filter({hasText:/fetch|network|gagal/i}).waitFor()
  assert.equal(sql(`SELECT count(*) FROM ai_snapshot WHERE unit_id='${unitId}'`),'0')
  await page.unroute('**/functions/v1/unit-explanation')
  await explanation.getByRole('button',{name:'Buat penjelasan berbasis bukti',exact:true}).click()
  await explanation.getByRole('status').filter({hasText:'Penjelasan dan bukti tersimpan'}).waitFor()
  await explanation.getByText(/Penjelasan aturan; layanan AI generatif belum dikonfigurasi/).waitFor()
  assert.equal(sql(`SELECT decision_payload->>'decision' FROM ai_snapshot WHERE unit_id='${unitId}'`),'PULIHKAN_DATA')
  await explanation.getByText('Lihat bukti penilaian',{exact:true}).click()
  await explanation.getByText(/Kode: PULIHKAN_DATA/).waitFor()
  report.push('Real persisted evidence explanation; stale/unsynced data holds advice; deliberate browser transport failure retains readings and creates no false snapshot')


  // Force only the local expiry metadata; the refresh request still reaches real Auth.
  await page.evaluate(()=>{
    const key=Object.keys(sessionStorage).find(x=>x.startsWith('smart-agro.account:'))
    const value=JSON.parse(sessionStorage.getItem(key));value.expires_at=Date.now()/1000-1;sessionStorage.setItem(key,JSON.stringify(value))
  })
  await page.reload()
  await panel.getByRole('listitem').filter({hasText:serial}).waitFor()
  report.push('expired local session refreshed through real Auth')
  await panel.getByRole('button',{name:'Keluar',exact:true}).click()
  await panel.getByRole('button',{name:'Masuk',exact:true}).waitFor()
  assert.equal(await panel.getByRole('listitem').count(),0)
  assert.equal(await telemetry(panel).count(),0)
  await panel.getByLabel('Email',{exact:true}).fill(email)
  await panel.getByLabel('Kata sandi',{exact:true}).fill(password)
  await panel.getByRole('button',{name:'Masuk',exact:true}).click()
  await panel.getByRole('listitem').filter({hasText:serial}).waitFor()
  report.push('logout clears account; real login restores owned product')
  await devicePanel.getByRole('combobox',{name:'Unit & perangkat milik saya',exact:true}).selectOption(unitKey)
  await devicePanel.locator('summary').filter({hasText:'3 bacaan terakhir'}).click()
  await mkdir('.tmp/phase1/browser',{recursive:true})
  for(const width of [1440,390,320]){
    await page.setViewportSize({width,height:1000})
    await panel.scrollIntoViewIfNeeded()
    const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1)
    assert.equal(overflow,false,`Horizontal overflow at ${width}`)
    await devicePanel.screenshot({path:`.tmp/phase1/browser/telemetry-${width}.png`})
    await panel.screenshot({path:`.tmp/phase1/browser/account-${width}.png`})
  }
  // Revoke through real Auth while the tab retains an unexpired access token.
  const staleToken=await page.evaluate(()=>JSON.parse(sessionStorage.getItem(Object.keys(sessionStorage).find(k=>k.startsWith('smart-agro.account:')))).access_token)
  const {anon}=JSON.parse(await readFile('.tmp/phase1/settings.json','utf8'))
  const revoked=await fetch('http://127.0.0.1:54321/auth/v1/logout?scope=local',{method:'POST',headers:{apikey:anon,Authorization:`Bearer ${staleToken}`}})
  assert.equal(revoked.status,204)
  await devicePanel.getByRole('button',{name:'Muat ulang bacaan',exact:true}).click()
  await panel.getByRole('button',{name:'Masuk',exact:true}).waitFor()
  assert.equal(await telemetry(panel).count(),0)
  assert.equal(await page.evaluate(()=>Object.keys(sessionStorage).some(k=>k.startsWith('smart-agro.account:'))),false)
  report.push('server-revoked unexpired session clears telemetry and local account on next read')
  assert.deepEqual(errors,[])
  await writeFile('.tmp/phase1/browser/report.json',JSON.stringify({checks:report,widths:[1440,390,320],errors},null,2))
  console.log(JSON.stringify({checks:report,widths:[1440,390,320],errors},null,2))
}catch(error){
  await mkdir('.tmp/phase1/browser',{recursive:true})
  await page.screenshot({path:'.tmp/phase1/browser/failure.png',fullPage:true})
  console.error(JSON.stringify({headings:await panel.locator('h3').allTextContents(),telemetryPanels:await telemetry(panel).count(),alerts:await panel.getByRole('alert').allTextContents()}))
  throw error
}finally{await browser.close()}
