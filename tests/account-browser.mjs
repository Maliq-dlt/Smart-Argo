  await panel.getByRole('list',{name:'Produk saya',exact:true}).getByRole('listitem').filter({hasText:serial}).waitFor()
  assert.equal(await panel.getByLabel('Kode aktivasi tersegel',{exact:true}).count(),0)
  await page.reload(); await curtainOpen(page); await profileSection(page,'Produk')
  await panel.getByRole('list',{name:'Produk saya',exact:true}).getByRole('listitem').filter({hasText:serial}).waitFor()
