import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright')
const url = process.env.TEST_URL || 'http://127.0.0.1:4173/'
const output = '.tmp/landing-restart'
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true, channel: 'chrome' })
const errors = [], report = []
const pause = async page => {
  let previous = '', stableSince = Date.now()
  for (const deadline = Date.now() + 6000; Date.now() < deadline;) {
    const state = await page.evaluate(() => JSON.stringify([scrollY, document.documentElement.scrollHeight, document.querySelector('.ag-specimen')?.getAttribute('style')]))
    if (state !== previous) { previous = state; stableSince = Date.now() }
    else if (Date.now() - stableSince >= 300) return
    await page.waitForTimeout(50)
  }
  assert.fail('Scroll and specimen did not settle within six seconds')
}
const fits = page => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)
try {
  for (const [width, height, reducedMotion] of [[1440, 900, 'no-preference'], [390, 844, 'no-preference'], [820, 900, 'no-preference'], [320, 740, 'no-preference'], [1440, 900, 'reduce'], [390, 844, 'reduce']]) {
    console.log(`Checking ${width}x${height}, ${reducedMotion}`)
    const page = await browser.newPage({ viewport: { width, height }, reducedMotion })
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    await page.goto(url)
    await page.getByRole('button', { name: 'Kenali tanaman ini', exact: true }).waitFor()
    await page.waitForFunction(() => [...document.querySelectorAll('.ag-landing img')].every(i => i.complete && i.naturalWidth > 0))
    await pause(page)
    assert(await fits(page), `Cover overflow at ${width}`)
    if (reducedMotion === 'no-preference' && [1440, 390].includes(width)) await page.screenshot({ path: `${output}/hero-${width}.png` })
    await page.getByRole('button', { name: 'Cabai', exact: true }).focus()
    await page.keyboard.press('ArrowRight')
    assert.equal(await page.getByRole('button', { name: 'Bawang', exact: true }).getAttribute('aria-pressed'), 'true')
    await page.keyboard.press('ArrowLeft')
    assert.equal(await page.getByRole('button', { name: 'Cabai', exact: true }).getAttribute('aria-pressed'), 'true')
    await page.getByRole('button', { name: 'Bawang', exact: true }).click()
    await pause(page)
    assert.match(await page.locator('h1').innerText(), /Bawang/i)
    const actor = await page.locator('.ag-specimen').elementHandle()
    const originalImage = await page.locator('.ag-specimen img').getAttribute('src')
    await page.getByRole('button', { name: 'Kenali tanaman ini', exact: true }).click()
    await pause(page)
    assert.equal(await page.locator('.ag-scene').count(), 5)
    if (reducedMotion === 'reduce' && width <= 900) {
      const separated = await page.evaluate(() => {
        const image = document.querySelector('#ritme .ag-still').getBoundingClientRect()
        return image.top >= 72 && image.bottom <= document.querySelector('.ag-intro-heading').getBoundingClientRect().top
      })
      assert(separated, 'Reduced-motion specimen clears the header and chapter text')
    }
    assert.equal(await page.getByRole('button', { name: 'Bawang', exact: true }).count(), 0)
    assert.equal(await page.locator('.ag-landing').getAttribute('data-crop'), 'bawang')
    if ([1440, 390].includes(width)) await page.screenshot({ path: `${output}/center-${width}-${reducedMotion}.png` })
    await page.getByRole('link', { name: /Amati$/ }).click()
    await pause(page)
    const observePose = await actor.evaluate(e => getComputedStyle(e).transform)
    const observeScroll = await page.evaluate(() => scrollY)
    await page.getByRole('slider', { name: /Geser waktu/ }).focus()
    await page.keyboard.press('Home')
    assert.equal(await page.locator('output').innerText(), '85')
    await page.keyboard.press('End')
    assert.equal(await page.locator('output').innerText(), '55')
    assert(await fits(page), `Observation overflow at ${width}`)
    if (reducedMotion === 'no-preference' && [1440, 390].includes(width)) await page.screenshot({ path: `${output}/observe-${width}.png` })
    await page.getByRole('link', { name: /Pahami$/ }).click()
    await pause(page)
    assert(await actor.evaluate(e => e.isConnected && e === document.querySelector('.ag-specimen')), 'Same specimen node survives the story')
    assert.equal(await page.locator('.ag-specimen img').getAttribute('src'), originalImage)
    if (reducedMotion === 'no-preference') assert.notEqual(await actor.evaluate(e => getComputedStyle(e).transform), observePose, 'Scroll moves the selected object')
    else assert.equal(await actor.evaluate(e => getComputedStyle(e).transform), observePose, 'Reduced motion keeps specimen static')
    await page.getByRole('button', { name: 'Cepat mengering', exact: true }).click()
    await page.getByRole('button', { name: 'Periksa dulu', exact: true }).click()
    await page.getByRole('status', { name: 'Alasan langkah perawatan' }).waitFor()
    assert.match(await page.getByRole('status', { name: 'Alasan langkah perawatan' }).innerText(), /pengamatan/i, 'Onion dry case uses onion profile')
    await page.getByRole('button', { name: 'Basah menetap', exact: true }).click()
    await page.getByRole('status', { name: 'Alasan langkah perawatan' }).waitFor({ state: 'detached' })
    await page.getByRole('button', { name: 'Periksa dulu', exact: true }).click()
    await pause(page)
    assert.match(await page.getByRole('status', { name: 'Alasan langkah perawatan' }).innerText(), /lubang pot.*genangan/s)
    assert(await fits(page), `Decision overflow at ${width}`)
    if (reducedMotion === 'no-preference' && [1440, 390].includes(width)) await page.screenshot({ path: `${output}/understand-${width}.png` })
    await page.getByRole('link', { name: /Amati$/ }).click()
    await pause(page)
    const restoredPose = await actor.evaluate(e => getComputedStyle(e).transform)
    const numbers = value => value === 'none' ? [] : value.slice(value.indexOf('(') + 1, -1).split(',').map(Number)
    assert.equal(await page.evaluate(() => scrollY), observeScroll, 'Reverse scroll returns to the same scroll coordinate')
    // Matrix coefficients are unitless; translation tolerates one tenth of a CSS pixel.
    assert(numbers(restoredPose).every((value, index) => Math.abs(value - numbers(observePose)[index]) < ([12, 13, 14].includes(index) ? .1 : .0001)), `Reverse scroll differs: ${JSON.stringify({ width, observeScroll, restoredScroll: await page.evaluate(() => scrollY), observePose, restoredPose })}`)
    await page.getByRole('link', { name: /Coba$/ }).click()
    await pause(page)
    if ([1440, 390].includes(width)) await page.screenshot({ path: `${output}/finish-${width}-${reducedMotion}.png` })
    assert.equal(await page.evaluate(() => localStorage.getItem('smart-agro.sessions.v1')), null, 'Story does not write simulator sessions')
    await page.getByRole('button', { name: 'Ganti tanaman', exact: true }).click()
    assert.equal(await page.locator('.ag-scene').count(), 1)
    await page.getByRole('button', { name: 'Cabai', exact: true }).click()
    await page.getByRole('button', { name: 'Kenali tanaman ini', exact: true }).click()
    await pause(page)
    await page.getByRole('link', { name: /Pahami$/ }).click()
    await pause(page)
    await page.getByRole('button', { name: 'Cepat mengering', exact: true }).click()
    await page.getByRole('button', { name: 'Periksa dulu', exact: true }).click()
    await pause(page)
    assert.match(await page.getByRole('status', { name: 'Alasan langkah perawatan' }).innerText(), /pergi|kunjungan/i, 'Chili profile produces its distinct advice')
    await page.getByRole('link', { name: 'Buka simulator', exact: true }).click()
    await page.getByRole('heading', { name: 'Ruang tanam', exact: true, level: 1 }).waitFor()
    assert.equal(await page.locator('.ag-stage, .ag-chapter-nav').count(), 0, 'Story stage is removed on simulator route')
    await page.getByRole('link', { name: /Smart Agro.*Beranda/ }).click()
    await page.getByRole('button', { name: 'Kenali tanaman ini', exact: true }).waitFor()
    assert(await fits(page), 'Return route has no overflow')
    assert.equal(await page.evaluate(() => document.documentElement.className.includes('lenis')), false)
    report.push({ width, height, reducedMotion, selection: 'pass', sameObject: 'pass', reverseScroll: 'pass', profileAdvice: 'pass', sessionPreserved: 'pass', simulatorRoute: 'pass', overflow: 'pass' })
    await page.close()
  }
  assert.deepEqual(errors, [])
  await writeFile(`${output}/browser-results.json`, JSON.stringify({ report, errors }, null, 2))
  console.log(JSON.stringify({ cases: report.length, errors, checks: 'selection, locked object, scroll/reverse, slider, crop-specific decisions, no session writes, simulator and return, reduced motion, overflow' }, null, 2))
} finally { await browser.close() }
