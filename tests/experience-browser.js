import assert from 'node:assert/strict'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { createJourney, plantSeed, advanceSimulation, canUndoWater } from '../src/lib/simulation.ts'
import { createSession, STORAGE_KEY } from '../src/lib/sessionStore.ts'
import { careEvents, chartSegments } from '../src/lib/chartData.ts'
import { clockDate, clockTime } from '../src/lib/sessionClock.ts'

const { chromium } = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright')
// The site curtain (loading screen) covers the first paint; interact only once it has lifted, like a visitor would.
const curtainOpen = page => page.waitForFunction(() => { const c = document.querySelector('.curtain'); return !c || c.dataset.state === 'open' })
const url = process.env.TEST_URL || 'http://127.0.0.1:4174/'
const output = '.tmp/experience-upgrade'
await mkdir(output, { recursive: true })
const cases = JSON.parse(await readFile('src/lib/scenarios.json', 'utf8'))
const browser = await chromium.launch({ headless: true, channel: 'chrome' })
const errors = [], report = []
const active = page => page.evaluate(key => {
  const book = JSON.parse(localStorage.getItem(key))
  return book.sessions.find(session => session.id === book.activeId)
}, STORAGE_KEY)
async function setup(width, theme, seed, hash = '#statistik') {
  const page = await browser.newPage({ viewport: { width, height: 1000 }, reducedMotion: width === 320 ? 'reduce' : 'no-preference' })
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(({ key, seed, theme }) => {
    if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify({ version: 1, activeId: seed.id, sessions: [seed] }))
    localStorage.setItem('smart-agro.theme', theme)
  }, { key: STORAGE_KEY, seed, theme })
  await page.goto(url + hash); await curtainOpen(page)
  await page.locator('.app-shell').waitFor()
  await page.waitForFunction(() => !document.documentElement.hasAttribute('data-site-transition'))
  return page
}
try {
  for (const [width, theme] of [[1440, 'light'], [820, 'dark'], [390, 'light'], [320, 'dark']]) {
    const seed = plantSeed(createJourney(cases[0]))
    const page = await setup(width, theme, seed)
    assert.equal(await page.locator('.observation-empty').count(), 1)
    assert.equal(await page.locator('.history-panel').count(), 0)
    const rootToggle = page.locator('.specimen-toggle')
    const original = await active(page)
    await rootToggle.click()
    assert.equal(await rootToggle.getAttribute('aria-pressed'), 'true')
    await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('.dashboard-specimen .plant-shell')).opacity) < .05)
    assert.deepEqual((await active(page)).data, original.data, 'Specimen is illustrative only')
    await rootToggle.click()
    await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('.dashboard-specimen .plant-shell')).opacity) > .95)
    await page.screenshot({ path: output + '/start-' + width + '-' + theme + '.png', fullPage: true })
    await page.getByRole('button', { name: 'Lanjutkan waktu', exact: true }).click()
    await page.locator('.history-panel').waitFor()
    await page.getByRole('button', { name: 'Jeda waktu', exact: true }).click()
    assert.equal(await page.locator('.observation-empty').count(), 0)
    await page.locator('.dashboard-care > a').click()
    await page.getByRole('heading', { name: 'Ruang tanam', exact: true, level: 1 }).waitFor()
    const before = await active(page)
    const view = page.getByRole('group', { name: 'Tampilan pot', exact: true })
    await view.getByRole('radio', { name: 'Tanaman', exact: true }).focus()
    await page.keyboard.press('ArrowRight')
    assert.equal(await view.getByRole('radio', { name: 'Penampang', exact: true }).isChecked(), true)
    await page.waitForFunction(() => getComputedStyle(document.querySelector('.plant-view-switch .segment:has(:checked) .segment-label')).color === getComputedStyle(document.body).color)
    await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('.plant-canvas .plant-shell')).opacity) < .05)
    assert.deepEqual((await active(page)).data, before.data, 'View switch never changes sensor data')
    await page.keyboard.press('ArrowLeft')
    await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('.plant-canvas .plant-shell')).opacity) > .95)
    const trend = page.locator('.studio-trend')
    assert.equal(await trend.getAttribute('open'), null)
    await trend.locator('summary').click()
    await trend.locator('svg[role=img]').waitFor({ state: 'visible' })
    await trend.locator('summary').click()
    assert.deepEqual((await active(page)).data, before.data, 'Trend disclosure is read-only')
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Studio fits/' + width)
    await page.screenshot({ path: '.tmp/21st-studio/studio-' + width + '-' + theme + '.png', fullPage: true })
    await page.getByRole('button', { name: 'Siram 150 mL', exact: true }).click()
    await page.locator('.pending-water').waitFor()
    await page.waitForTimeout(700)
    const pending = await active(page)
    assert.deepEqual(pending.data.samples, before.data.samples, 'Water pauses the next sample')
    assert.equal(pending.data.now_h, before.data.now_h)
    assert(canUndoWater(pending))
    assert.equal(await page.getByRole('button', { name: 'Siram 150 mL', exact: true }).isDisabled(), true)
    await page.reload()
    await page.locator('.pending-water').waitFor()
    await page.waitForFunction(() => !document.documentElement.hasAttribute('data-site-transition'))
    assert(canUndoWater(await active(page)), 'Undo survives refresh')
    if (width === 320) await page.addStyleTag({ content: 'html { font-size: 200% !important; }' })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No pending overflow/' + width)
    const undo = page.getByRole('button', { name: 'Batalkan siraman', exact: true })
    assert(await undo.evaluate(button => button.getBoundingClientRect().height >= 44))
    await page.locator('.pending-water').screenshot({ path: output + '/pending-' + width + '-' + theme + '.png' })
    await undo.focus(); await page.keyboard.press('Enter')
    await page.locator('.pending-water').waitFor({ state: 'hidden' })
    const undone = await active(page)
    assert.deepEqual(undone.data, before.data)
    assert.equal(careEvents(undone.logs, undone.data).filter(event => event.kind === 'water').length, 0)
    assert.equal(await page.evaluate(() => document.activeElement?.textContent), 'Siram 150 mL')
    await page.getByRole('button', { name: 'Siram 150 mL', exact: true }).click()
    await page.getByRole('button', { name: 'Lanjutkan waktu', exact: true }).click()
    await page.locator('.pending-water').waitFor({ state: 'hidden' })
    await page.getByRole('button', { name: 'Jeda', exact: true }).click()
    assert(!canUndoWater(await active(page)), 'Processed water cannot be undone')
    report.push({ width, theme, initialObservation: 'pass', undoRefresh: 'pass', keyboardFocus: 'pass', consumedWater: 'pass', overflow: false })
    await page.close()
  }
  const empty = await setup(390, 'light', createJourney(cases[0]))
  assert.match(await empty.locator('.observation-empty').innerText(), /Mulai dari bibit/)
  await empty.close()
  const manual = await setup(390, 'light', createSession(cases[0], 'Catatan manual'), '#simulasi')
  const manualBefore = await active(manual)
  await manual.getByRole('button', { name: 'Catat siram', exact: true }).click()
  await manual.locator('.pending-water').waitFor()
  assert.equal((await active(manual)).simulation.pendingWater, 0)
  await manual.getByRole('button', { name: 'Batalkan siraman', exact: true }).click()
  assert.deepEqual((await active(manual)).data, manualBefore.data)
  await manual.getByRole('button', { name: 'Catat siram', exact: true }).click()
  await manual.getByRole('button', { name: /Tambah sampel/ }).click()
  await manual.locator('.pending-water').waitFor({ state: 'hidden' })
  assert.equal((await active(manual)).simulation.waterUndo, undefined)
  await manual.close()

  let seed = advanceSimulation(plantSeed(createJourney(cases[0])), 32)
  seed.data.samples[4].valid = false
  for (const theme of ['light', 'dark']) {
    const page = await setup(1440, theme, seed)
    const snapshot = await active(page)
    if (theme === 'light') await page.getByRole('button', { name: 'Panduan', exact: true }).click()
    await page.evaluate(() => window.dispatchEvent(new Event('beforeprint')))
    await page.emulateMedia({ media: 'print' })
    await page.locator('.session-report').waitFor()
    const text = await page.locator('.session-report').innerText()
    assert(text.includes(snapshot.name))
    assert(text.includes(clockDate(snapshot.clock, snapshot.data.now_h) + ' ' + clockTime(snapshot.clock, snapshot.data.now_h)))
    assert(text.includes(snapshot.data.samples.at(-1).moisture.toLocaleString('id-ID', { maximumFractionDigits: 1 })))
    assert.equal(await page.locator('.session-report svg polyline').count(), chartSegments(snapshot.data.samples, 'moisture').length)
    assert.equal(await page.locator('.app-shell').isVisible(), false)
    assert.equal(await page.locator('.session-report button').count(), 0)
    assert.equal(await page.locator('.session-report').evaluate(report => getComputedStyle(report).backgroundColor), 'rgb(255, 255, 255)')
    await page.screenshot({ path: output + '/print-' + theme + '.png', fullPage: true })
    await page.pdf({ path: output + '/session-' + theme + '.pdf', preferCSSPageSize: true })
    assert.deepEqual((await active(page)).data, snapshot.data, 'Printing never changes samples')
    await page.emulateMedia({ media: 'screen' })
    await page.locator('.session-report').waitFor({ state: 'detached' })
    if (theme === 'light') await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'Berkas', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: 'Ringkasan cetak', exact: true }).count(), 1)
    await page.keyboard.press('Escape')
    await page.close()
  }
  // Verify print freezes a running clock and resume is explicit.
  const printing = await setup(820, 'light', seed)
  await printing.getByRole('button', { name: 'Lanjutkan waktu', exact: true }).click()
  await printing.evaluate(() => window.dispatchEvent(new Event('beforeprint')))
  const frozen = await active(printing)
  await printing.waitForTimeout(700)
  assert.deepEqual((await active(printing)).data, frozen.data)
  assert.match(await printing.locator('.clock-pause-note').innerText(), /ringkasan cetak/)
  await printing.evaluate(() => window.dispatchEvent(new Event('afterprint')))
  await printing.close()
  for (const [width, reducedMotion] of [[1440, 'no-preference'], [820, 'no-preference'], [390, 'reduce'], [320, 'reduce']]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 }, reducedMotion })
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(url); await curtainOpen(page)
    const timeline = page.getByRole('group', { name: 'Perjalanan proyek Smart Agro', exact: true })
    await timeline.getByRole('button', { name: 'Konsep', exact: true }).focus()
    await page.keyboard.press('ArrowRight')
    assert.match(await page.locator('.origin-milestone[data-active=true]').innerText(), /Bacaan perlu punya alasan/)
    await page.waitForFunction(() => Number(getComputedStyle(document.querySelector('.origin-visual .plant-shell')).opacity) < .05)
    assert.equal(await timeline.getByRole('button', { name: 'Aturan', exact: true }).getAttribute('aria-expanded'), 'true')
    assert.equal(await timeline.locator('button[aria-expanded=true]').count(), 1)
    assert(await timeline.locator('button').evaluateAll(buttons => buttons.every(button => document.getElementById(button.getAttribute('aria-controls')))), 'Every milestone references an existing panel')
    await page.keyboard.press('ArrowRight')
    assert.match(await page.locator('.origin-milestone[data-active=true]').innerText(), /Sebuah ide, bisa kamu coba/)
    assert.equal(await page.locator('.origin-visual .plant-shell').getAttribute('opacity'), '0.25')
    assert.equal(await page.evaluate(key => localStorage.getItem(key), STORAGE_KEY), null, 'Story creates no session')
    if (width === 320) await page.addStyleTag({ content: 'html { font-size: 200% !important; }' })
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Story fits/' + width)
    assert(await page.locator('#project-origin-title').evaluate(heading => heading.scrollWidth <= heading.clientWidth), 'Story heading is readable at enlarged text/' + width)
    const bounds = await timeline.locator('button').evaluateAll(buttons => buttons.map(button => ({ width: button.clientWidth, scroll: button.scrollWidth, height: button.clientHeight })))
    assert(bounds.every(button => button.height >= 44 && button.scroll <= button.width), 'Timeline labels and targets fit/' + width)
    if (reducedMotion === 'reduce') assert.equal(await page.locator('#origin-detail').evaluate(el => getComputedStyle(el).animationName), 'none')
    await page.locator('#asal-usul').screenshot({ path: output + '/story-' + width + '.png' })
    await page.close()
  }
  assert.deepEqual(errors, [])
  await writeFile(output + '/browser-report.json', JSON.stringify({ report, manual: 'pass', print: 'pass', errors }, null, 2))
  console.log('Experience OK: four viewports/themes, empty state, pending pause, refresh undo, keyboard focus, manual recording, 200% text, real PDF in light/dark, print freezes clock, no page errors.')
} finally { await browser.close() }
